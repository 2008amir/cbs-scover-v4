const test = require('node:test');
const assert = require('node:assert/strict');
const { generateImage, imageBuffer, handleCreate } = require('./image-generation');
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64');
const payload = { candidates: [{ content: { parts: [{ text: 'Here is your image' }, { inlineData: { mimeType: 'image/png', data: png.toString('base64') } }] } }] };

test('create sends generated bytes and completion reaction to the original chat', async () => {
    const sent = [];
    const socket = { sendMessage: async (chat, content, options) => { sent.push({ chat, content, options }); } };
    const message = { chat: 'test@s.whatsapp.net', key: { id: 'create-test' } };
    await handleCreate(socket, message, 'a red apple', '.create', {
        generate: prompt => generateImage(prompt, { getKeys: async () => ['test-key'], http: { post: async (url, body, options) => {
            assert.match(url, /gemini-3\.1-flash-image:generateContent$/);
            assert.equal(body.contents[0].parts[0].text, 'a red apple');
            assert.equal(options.headers['x-goog-api-key'], 'test-key');
            assert.ok(options.timeout <= 45000);
            return { status: 200, data: payload };
        } } })
    });
    assert.deepEqual(sent[1].content.image, png);
    assert.equal(sent[1].chat, message.chat);
    assert.equal(sent[1].options.quoted, message);
    assert.equal(sent[2].content.react.text, '✅');
});

test('rotates unavailable chat keys without losing the prompt', async () => {
    const attempted = [];
    const result = await generateImage('cat', { getKeys: async () => ['test-one', 'test-two', 'test-three'], http: { post: async (url, body, options) => {
        attempted.push(options.headers['x-goog-api-key']);
        return attempted.length === 1 ? { status: 403 } : attempted.length === 2 ? { status: 429 } : { status: 200, data: payload };
    } } });
    assert.deepEqual(attempted, ['test-one', 'test-two', 'test-three']);
    assert.deepEqual(result, png);
});

test('missing credentials stop before making network requests', async () => {
    await assert.rejects(generateImage('cat', { getKeys: async () => [], http: { post: () => assert.fail('Unexpected request') } }), { code: 'MISSING_KEY' });
});

test('HTML and invalid inline data never become WhatsApp images', () => {
    assert.equal(imageBuffer({ candidates: [{ content: { parts: [{ inlineData: { mimeType: 'image/png', data: Buffer.from('<html>404</html>').toString('base64') } }] } }] }), null);
});

test('blocked responses are not retried using another key', async () => {
    let requests = 0;
    await assert.rejects(generateImage('cat', { getKeys: async () => ['one', 'two'], http: { post: async () => {
        requests++;
        return { status: 200, data: { promptFeedback: { blockReason: 'SAFETY' } } };
    } } }), { code: 'BLOCKED' });
    assert.equal(requests, 1);
});

test('provider exceptions do not leak credentials into errors', async () => {
    await assert.rejects(generateImage('cat', { getKeys: async () => ['test-secret'], http: { post: async () => { throw new Error('test-secret'); } } }), error => error.code === 'UNAVAILABLE' && !error.message.includes('test-secret'));
});